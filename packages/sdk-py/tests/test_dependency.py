# --- the consent path -----------------------------------------------------


def _fake_io(answer: str, result: AddResult):
    runs: list[tuple[str, list[str], str]] = []
    questions: list[str] = []

    def read_line(question: str, fallback: str) -> str:
        questions.append(question)
        return answer

    def run(bin_name: str, args: list[str], cwd: str) -> AddResult:
        runs.append((bin_name, args, cwd))
        return result

    return DependencyIO(read_line=read_line, run=run), runs, questions


def _offer(
    capsys, fixture: str, interactive: bool, answer: str = "", result: AddResult | None = None
):
    root = str(CASES / fixture)
    io, runs, _ = _fake_io(answer, result or AddResult(started=True))
    offer = offer_dependency(root, detect_ecosystem(root), interactive, io)
    return offer, capsys.readouterr().out, runs


def test_offer_yes_runs_the_manager(capsys) -> None:
    offer, out, runs = _offer(capsys, "node-pnpm-lock", True, "y")
    assert runs == [("pnpm", ["add", "-D", "@leji-org/leji"], str(CASES / "node-pnpm-lock"))]
    assert "Detected pnpm (pnpm-lock.yaml)." in out
    assert consent_disclosure("pnpm") in out
    assert "Running: pnpm add -D @leji-org/leji" in out
    assert "Declared @leji-org/leji; a clean install now brings leji." in out
    assert offer == DependencyOffer(
        offered=True,
        ran=True,
        command=["pnpm", "add", "-D", "@leji-org/leji"],
        exit_code=0,
        signal=None,
    )
    assert not dependency_add_failed(offer)


def test_disclosure_precedes_the_prompt(capsys) -> None:
    _, out, _ = _offer(capsys, "node-pnpm-lock", True, "n")
    assert out.index("Detected pnpm") < out.index(consent_disclosure("pnpm"))
    offer, quiet, runs = _offer(capsys, "node-pnpm-lock", False, "y")
    assert "This runs" not in quiet and runs == []
    # Nothing ran, so there is no exit code and no signal to report.
    assert offer == DependencyOffer(
        offered=True,
        ran=False,
        command=["pnpm", "add", "-D", "@leji-org/leji"],
        exit_code=None,
        signal=None,
    )
    for fixture, binary in (("python-uv", "uv"), ("go-1.24", "go"), ("node-npm-lock", "npm")):
        _, text, _ = _offer(capsys, fixture, True, "n")
        assert consent_disclosure(binary) in text


def test_decline_runs_nothing(capsys) -> None:
    for answer in ("n", "no", "q", "N"):
        offer, out, runs = _offer(capsys, "node-pnpm-lock", True, answer)
        assert runs == [] and not dependency_add_failed(offer)
        assert offer == DependencyOffer(
            offered=True,
            ran=False,
            command=["pnpm", "add", "-D", "@leji-org/leji"],
            exit_code=None,
            signal=None,
        )
        assert "Skipped; declare it later with:\n   pnpm add -D @leji-org/leji" in out


def test_failure_branches(capsys) -> None:
    offer, out, _ = _offer(capsys, "python-uv", True, "y", AddResult(started=True, exit_code=1))
    assert "uv exited 1; run it yourself:\n   uv add --dev leji" in out
    assert offer == DependencyOffer(
        offered=True, ran=True, command=["uv", "add", "--dev", "leji"], exit_code=1, signal=None
    )
    assert dependency_add_failed(offer)

    # A signalled manager has no exit code of its own: the signal is the outcome.
    offer, out, _ = _offer(
        capsys, "go-1.24", True, "y", AddResult(started=True, exit_code=-1, signal="SIGTERM")
    )
    assert "go was terminated (SIGTERM); run it yourself:" in out
    assert offer == DependencyOffer(
        offered=True,
        ran=True,
        command=["go", "get", "-tool", "github.com/leji-org/leji/packages/sdk-go/cmd/leji@latest"],
        exit_code=None,
        signal="SIGTERM",
    )
    assert dependency_add_failed(offer)

    # A spawn that never started carries neither an exit code nor a signal, and is
    # still a failure: reading its null exit code as success would pass a run in
    # which nothing happened.
    offer, out, _ = _offer(capsys, "node-npm-lock", True, "y", AddResult(started=False))
    assert "npm is not on your PATH; run it yourself once it is:\n   npm i -D @leji-org/leji" in out
    assert offer == DependencyOffer(
        offered=True,
        ran=True,
        command=["npm", "i", "-D", "@leji-org/leji"],
        exit_code=None,
        signal=None,
    )
    assert dependency_add_failed(offer)


def test_signal_name_is_canonical_across_runtimes() -> None:
    """Python reports a signalled child as a negative return code; the runner turns
    that into the canonical name the other two SDKs print."""
    import subprocess

    from leji.dependency import default_dependency_io

    io = default_dependency_io()
    result = io.run("sh", ["-c", "kill -TERM $$"], ".")
    assert result.started and result.signal == "SIGTERM" and result.exit_code == -1
    assert subprocess.run(["sh", "-c", "kill -TERM $$"]).returncode == -15
    clean = io.run("sh", ["-c", "exit 7"], ".")
    assert clean.started and clean.exit_code == 7 and clean.signal == ""
    missing = io.run("leji-no-such-binary-xyz", [], ".")
    assert not missing.started


def test_never_prompts_without_a_command(capsys) -> None:
    offer, out, runs = _offer(capsys, "node-declared", True, "y")
    assert runs == []
    # `command` still names the add this repository would use; `offered` is what
    # says there is nothing to consent to, because the CLI is already declared.
    assert offer == DependencyOffer(
        offered=False,
        ran=False,
        command=["npm", "i", "-D", "@leji-org/leji"],
        exit_code=None,
        signal=None,
    )
    assert out.strip() == "The Leji CLI is already declared in package.json."
    for fixture in (
        "python-bare-pyproject",
        "python-requirements-only",
        "go-1.23-legacy",
        "node-two-lockfiles",
        "node-refused-evidence",
        "node-unreadable-manifest",
        "node-packagemanager-unknown",
        "none",
        "multiple-ecosystems",
        "composite-ambiguity",
    ):
        offer, _, runs = _offer(capsys, fixture, True, "y")
        assert runs == [], fixture
        assert not offer.offered and not offer.ran and not dependency_add_failed(offer), fixture


def test_hook_uses_the_detected_runner(tmp_path: Path) -> None:
    import subprocess

    root = plant(tmp_path, dict(LOCAL_ROOTS["pnpm"]), "hookrepo")
    subprocess.run(["git", "init", "-q"], cwd=root, check=True)
    result = ensure_local_hook(str(root))
    assert result.action == "created"
    assert (root / result.path).read_text(encoding="utf-8") == golden("hook-pnpm.sh")
    assert ensure_local_hook(str(root)).action == "unchanged"
    # And the runner the report chooses is what the hook carries.
    assert runner_argv(detect_ecosystem(str(root))) == ["pnpm", "exec", "leji"]


def test_resolve_ci_job_is_local_only_when_declared_and_locked(tmp_path: Path) -> None:
    declared_locked = detect_ecosystem(str(plant(tmp_path, dict(LOCAL_ROOTS["pnpm"]), "dl")))
    assert resolve_ci_job(declared_locked, "github").local is True
    unlocked = detect_ecosystem(str(plant(tmp_path, {"package.json": DECLARED_PKG}, "ul")))
    assert resolve_ci_job(unlocked, "github").local is False
    assert build_ci_file("github", resolve_ci_job(unlocked, "github")) == golden(
        "github-node-fallback.yml"
    )
