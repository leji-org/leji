@pytest.mark.parametrize("manager", sorted(LOCAL_ROOTS))
@pytest.mark.parametrize("provider", CI_PROVIDERS)
def test_ci_table_local_jobs(tmp_path: Path, manager: str, provider: str) -> None:
    root = plant(tmp_path, LOCAL_ROOTS[manager], f"{manager}-{provider}")
    result = ensure_ci_workflow(str(root), provider)
    assert result.action == "created"
    assert (root / CI_REL[provider]).read_text(encoding="utf-8") == golden(
        f"{provider}-{manager}-local.yml"
    )


def test_ci_table_fallbacks(tmp_path: Path) -> None:
    cases = [
        ({"package.json": DECLARED_PKG}, "node-fallback"),
        ({"package.json": '{"name":"demo"}\n', "package-lock.json": ""}, "node-fallback"),
        ({"package.json": "{}\n", "package-lock.json": "", "yarn.lock": ""}, "node-fallback"),
        ({"package.json": '{"packageManager":"hermit@1.0.0"}\n'}, "node-fallback"),
        ({"pyproject.toml": '[project]\nname = "d"\nversion = "0"\n'}, "python-fallback"),
        ({"requirements.txt": "requests\n"}, "python-fallback"),
        ({"go.mod": "module example.com/d\n\ngo 1.23\n"}, "go-fallback"),
        ({"go.mod": "module example.com/d\n\ngo 1.24.0\n"}, "go-fallback"),
        (
            {"package.json": "{}\n", "pyproject.toml": '[project]\nname="d"\nversion="0"\n'},
            "node-fallback",
        ),
    ]
    for i, (files, key) in enumerate(cases):
        root = plant(tmp_path, files, f"fb{i}")
        ensure_ci_workflow(str(root), "github")
        assert (root / CI_REL["github"]).read_text(encoding="utf-8") == golden(
            f"github-{key}.yml"
        ), key


# --- ownership ------------------------------------------------------------


def test_ci_ownership_upgrades_a_legacy_file(tmp_path: Path) -> None:
    for provider in ("github", "circleci", "azure"):
        for mode in ("local", "fallback"):
            root = plant(tmp_path, dict(LOCAL_ROOTS["pnpm"]), f"legacy-{provider}-{mode}")
            target = root / CI_REL[provider]
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(golden(f"legacy-1.3-{provider}-{mode}.yml"), encoding="utf-8")
            result = ensure_ci_workflow(str(root), provider)
            assert result.action == "updated", f"{provider}/{mode}"
            assert target.read_text(encoding="utf-8") == golden(f"{provider}-pnpm-local.yml")


def test_ci_ownership_idempotent_and_manager_change(tmp_path: Path) -> None:
    for provider in CI_PROVIDERS:
        root = plant(tmp_path, dict(LOCAL_ROOTS["uv"]), f"idem-{provider}")
        assert ensure_ci_workflow(str(root), provider).action == "created"
        after = (root / CI_REL[provider]).read_text(encoding="utf-8")
        assert ensure_ci_workflow(str(root), provider).action == "unchanged"
        assert (root / CI_REL[provider]).read_text(encoding="utf-8") == after

    change = plant(tmp_path, dict(LOCAL_ROOTS["pnpm"]), "manager-change")
    target = change / CI_REL["github"]
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(golden("github-npm-local.yml"), encoding="utf-8")
    assert ensure_ci_workflow(str(change), "github").action == "updated"
    assert target.read_text(encoding="utf-8") == golden("github-pnpm-local.yml")


def test_ci_ownership_leaves_edited_and_foreign_files_alone(tmp_path: Path) -> None:
    for provider in ("github", "circleci", "azure"):
        edited = plant(tmp_path, dict(LOCAL_ROOTS["pnpm"]), f"edited-{provider}")
        mine = golden(f"{provider}-pnpm-local.yml")
        target = edited / CI_REL[provider]
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(mine + "      - run: echo mine\n", encoding="utf-8")
        result = ensure_ci_workflow(str(edited), provider)
        assert result.action == "manual" and result.snippet
        assert target.read_text(encoding="utf-8") == mine + "      - run: echo mine\n"

        foreign = plant(tmp_path, dict(LOCAL_ROOTS["pnpm"]), f"foreign-{provider}")
        ftarget = foreign / CI_REL[provider]
        ftarget.parent.mkdir(parents=True, exist_ok=True)
        ftarget.write_text("name: someone-elses-pipeline\n", encoding="utf-8")
        assert ensure_ci_workflow(str(foreign), provider).action == "manual"
        assert ftarget.read_text(encoding="utf-8") == "name: someone-elses-pipeline\n"


def test_ci_ownership_is_provider_scoped(tmp_path: Path) -> None:
    """The same bytes are leji's at one provider's path and somebody else's at
    another's, so a digest match must be provider-scoped."""
    cross = [
        ("github", "legacy-1.3-circleci-local.yml"),
        ("github", "legacy-1.3-azure-fallback.yml"),
        ("circleci", "legacy-1.3-github-local.yml"),
        ("circleci", "legacy-1.3-azure-local.yml"),
        ("azure", "legacy-1.3-github-fallback.yml"),
        ("azure", "legacy-1.3-circleci-fallback.yml"),
    ]
    for i, (provider, foreign) in enumerate(cross):
        root = plant(tmp_path, dict(LOCAL_ROOTS["pnpm"]), f"cross{i}")
        target = root / CI_REL[provider]
        target.parent.mkdir(parents=True, exist_ok=True)
        body = golden(foreign)
        target.write_text(body, encoding="utf-8")
        assert ensure_ci_workflow(str(root), provider).action == "manual", f"{foreign}@{provider}"
        assert target.read_text(encoding="utf-8") == body
    for provider in ("github", "circleci", "azure"):
        root = plant(tmp_path, dict(LOCAL_ROOTS["pnpm"]), f"own-{provider}")
        target = root / CI_REL[provider]
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(golden(f"legacy-1.3-{provider}-local.yml"), encoding="utf-8")
        assert ensure_ci_workflow(str(root), provider).action == "updated"


def test_gitlab_owns_only_its_block(tmp_path: Path) -> None:
    root = plant(tmp_path, dict(LOCAL_ROOTS["pnpm"]), "gitlab-merge")
    target = root / ".gitlab-ci.yml"
    target.write_text("stages:\n  - test\n", encoding="utf-8")
    assert ensure_ci_workflow(str(root), "gitlab").action == "updated"
