def golden(name: str) -> str:
    return (GOLDENS / name).read_text(encoding="utf-8")


def plant(tmp_path: Path, files: dict[str, str], name: str = "root") -> Path:
    root = tmp_path / name
    root.mkdir(parents=True, exist_ok=True)
    for rel, body in files.items():
        (root / rel).write_text(body, encoding="utf-8")
    return root


# --- the goldens ----------------------------------------------------------


def test_ci_variants_match_goldens() -> None:
    variants = ci_variants()
    assert len(variants) == len(CI_PROVIDERS) * 12
    for provider, key, body in variants:
        assert body == golden(f"{provider}-{key}.yml"), f"{provider}/{key}"


def test_hook_goldens() -> None:
    for manager in MANAGERS:
        argv = manager_runner_argv(manager)
        assert argv is not None
        assert hook_body(argv) == golden(f"hook-{manager}.sh"), manager
        assert husky_block(argv) == golden(f"husky-{manager}.sh"), manager
    assert hook_body(["leji"]) == golden("hook-fallback.sh")
    assert husky_block(["leji"]) == golden("husky-fallback.sh")


def test_sh_quote_and_hook_shape() -> None:
    assert sh_quote("pnpm") == "'pnpm'"
    assert sh_quote("we'ird") == "'we'\\''ird'"
    assert sh_quote("a b") == "'a b'"
    assert sh_quote("x$HOME") == "'x$HOME'"
    body = hook_body(["weird bin", "quo'te", "$HOME", "`cmd`", "*"])
    assert "'weird bin' 'quo'\\''te' '$HOME' '`cmd`' '*' validate || exit 1" in body
    assert "echo 'leji: stored index is stale; run `leji index` and stage the result.' >&2" in body
    for argv in (["leji"], ["pnpm", "exec", "leji"], ["go", "tool", "leji"]):
        for gone in ("node_modules", "LEJI=", "$LEJI"):
            assert gone not in hook_body(argv)
            assert gone not in husky_block(argv)


def test_marker_and_legacy_job() -> None:
    for provider, key, body in ci_variants():
        if provider == "gitlab":
            assert "generated by leji ci (managed)" not in body
            assert body.startswith("# >>> leji ci (managed) >>>\n")
        else:
            assert body.startswith(CI_MARKER + "\n"), f"{provider}/{key}"
    for provider in ("github", "circleci", "azure"):
        before = golden(f"legacy-1.3-{provider}-fallback.yml")
        assert golden(f"{provider}-node-fallback.yml") == CI_MARKER + "\n" + before


def test_unpinned_disclosure_appears_once_only_where_earned() -> None:
    for provider, key, body in ci_variants():
        hits = [line for line in body.split("\n") if "is installed unpinned here" in line]
        wants = key in ("poetry-local", "pdm-local", "pipenv-local") or (
            key == "uv-local" and provider != "github"
        )
        assert len(hits) == (1 if wants else 0), f"{provider}/{key}"
    assert "astral-sh/setup-uv@v5" in golden("github-uv-local.yml")
    assert "pip install uv" not in golden("github-uv-local.yml")
    assert "pip install uv && uv sync --locked" in golden("gitlab-uv-local.yml")


